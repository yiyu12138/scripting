/** 把字符串编成 Code128-B 的模块串（1 = 黑条，0 = 空）。只支持可见 ASCII。 */
export function code128B(value: string): string {
  const chars = Array.from(value)
  if (chars.length === 0) throw new Error("没有码值")
  const codes: number[] = [104] // 起始符 B
  for (const ch of chars) {
    const c = ch.charCodeAt(0)
    if (c < 32 || c > 126) throw new Error("码值里有条形码不支持的字符")
    codes.push(c - 32)
  }
  // 校验位：起始符 + Σ(第 i 个数据符 × i)，对 103 取余
  let sum = 104
  for (let i = 1; i < codes.length; i++) sum += codes[i] * i
  codes.push(sum % 103)
  codes.push(106) // 终止符
  return codes.map(n => BARS[n]).join("")
}

/** 相邻同色模块合并成「条/空 + 宽度」，减少要画的视图数量。 */
export function barRuns(modules: string): { black: boolean; width: number }[] {
  const out: { black: boolean; width: number }[] = []
  for (const m of modules) {
    const black = m === "1"
    const last = out[out.length - 1]
    if (last && last.black === black) last.width++
    else out.push({ black, width: 1 })
  }
  return out
}
